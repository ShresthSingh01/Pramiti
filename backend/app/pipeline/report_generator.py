from fpdf import FPDF
from pathlib import Path
from typing import Dict, Any, List

class AICTEValidationReport(FPDF):
    def header(self):
        self.set_font('helvetica', 'B', 15)
        self.cell(0, 10, 'ALL INDIA COUNCIL FOR TECHNICAL EDUCATION (AICTE)', align='C', new_x="LMARGIN", new_y="NEXT")
        self.set_font('helvetica', 'I', 10)
        self.cell(0, 6, 'Autonomous Statutory Body, Ministry of Education, Govt. of India', align='C', new_x="LMARGIN", new_y="NEXT")
        self.cell(0, 6, 'Preliminary Application Scrutiny & Regulatory Verification Report (APH 2025-26)', align='C', new_x="LMARGIN", new_y="NEXT")
        self.ln(5)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(5)

    def footer(self):
        self.set_y(-15)
        self.set_font('helvetica', 'I', 8)
        self.cell(0, 10, f'Page {self.page_no()} | Generated by PRAMITI (Decision-Support Only - Subject to Competent Authority)', align='C')

def generate_validation_pdf(app_data: Dict[str, Any], findings: List[Dict[str, Any]], output_path: str):
    pdf = AICTEValidationReport()
    pdf.add_page()
    
    # Institution Summary
    pdf.set_font('helvetica', 'B', 12)
    pdf.cell(0, 8, '1. INSTITUTION & APPLICATION SUMMARY', new_x="LMARGIN", new_y="NEXT")
    pdf.set_font('helvetica', '', 10)
    pdf.cell(50, 6, 'Application ID:', border=0)
    pdf.cell(0, 6, str(app_data.get('id', 'N/A')), new_x="LMARGIN", new_y="NEXT")
    pdf.cell(50, 6, 'Institution Name:', border=0)
    pdf.cell(0, 6, str(app_data.get('institutionName', 'N/A')), new_x="LMARGIN", new_y="NEXT")
    pdf.cell(50, 6, 'Approval Category:', border=0)
    pdf.cell(0, 6, str(app_data.get('category', 'EoA Renewal')), new_x="LMARGIN", new_y="NEXT")
    pdf.cell(50, 6, 'Computed Risk Score:', border=0)
    pdf.cell(0, 6, f"{app_data.get('riskScore', 'N/A')} / 100", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(5)

    # Findings
    pdf.set_font('helvetica', 'B', 12)
    pdf.cell(0, 8, f'2. SCRUTINY OBSERVATIONS & CLAUSE CITATIONS ({len(findings)} Findings)', new_x="LMARGIN", new_y="NEXT")
    
    if not findings:
        pdf.set_font('helvetica', 'I', 10)
        pdf.cell(0, 8, 'No regulatory non-compliances or anomalies identified.', new_x="LMARGIN", new_y="NEXT")
    else:
        for f in findings:
            pdf.set_font('helvetica', 'B', 10)
            sev = f.get('severity', 'medium').upper()
            pdf.cell(0, 6, f"[{sev}] {f.get('title')}", new_x="LMARGIN", new_y="NEXT")
            pdf.set_font('helvetica', 'I', 9)
            pdf.cell(0, 5, f"Rule Reference: {f.get('clause_ref')} (Handbook {f.get('handbook_version')})", new_x="LMARGIN", new_y="NEXT")
            pdf.set_font('helvetica', '', 9)
            pdf.multi_cell(0, 5, f"Finding: {f.get('description')}")
            if f.get('suggested_fix'):
                pdf.set_font('helvetica', 'B', 9)
                pdf.cell(30, 5, 'Suggested Action: ')
                pdf.set_font('helvetica', '', 9)
                pdf.multi_cell(0, 5, f.get('suggested_fix'))
            pdf.ln(3)

    pdf.output(output_path)
    return output_path
